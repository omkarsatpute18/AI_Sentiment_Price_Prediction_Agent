
import json
import os
import time
from pathlib import Path

from dotenv import load_dotenv
from google import genai
from google.genai import types


# --------------------------------------------------
# CONFIGURATION
# --------------------------------------------------

ROOT_DIR = Path(__file__).resolve().parents[2]

load_dotenv(ROOT_DIR / ".env")

GEMINI_MODEL = "gemini-3.8-flash"

MAX_RETRIES = 3
RETRY_DELAY = 2

RETRYABLE_STATUS_CODES = {429, 500, 502, 503, 504}


# --------------------------------------------------
# INITIALIZE GEMINI CLIENT
# --------------------------------------------------

def get_gemini_client():

    api_key = os.getenv("GEMINI_API_KEY")

    if not api_key:
        raise ValueError(
            "GEMINI_API_KEY is missing. "
            "Please configure it in your project's .env file."
        )

    return genai.Client(api_key=api_key)


# --------------------------------------------------
# SYSTEM INSTRUCTIONS
# --------------------------------------------------

SYSTEM_INSTRUCTION = """
You are an AI Stock Market Research Assistant.

You are part of an academic project that analyzes stocks
listed in Hong Kong and South Korea.

Your responsibilities:

1. Explain stock price movements using the supplied data.
2. Explain technical indicators such as RSI, MACD,
   moving averages and trading volume.
3. Interpret financial and business social sentiment.
4. Explain predictions generated by the project's ML models.
5. Help users understand stock market concepts.

IMPORTANT RULES:

- Use the supplied stock data as your factual source.
- Never invent stock prices, dates, sentiment scores or predictions.
- If information is unavailable, clearly say so.
- Distinguish observed facts from your own interpretation.
- Explain technical terms in simple English.
- Do not guarantee future stock performance.
- Do not present experimental predictions as financial advice.
- The current ML models use technical indicators only.
  They do not use social sentiment as model inputs.
- Mention limitations when relevant.
- Keep answers clear, helpful and reasonably concise.
"""


# --------------------------------------------------
# CHECK WHETHER AN ERROR CAN BE RETRIED
# --------------------------------------------------

def is_retryable_error(error):

    status_code = (
        getattr(error, "code", None)
        or getattr(error, "status_code", None)
    )

    if status_code in RETRYABLE_STATUS_CODES:
        return True

    error_message = str(error).lower()

    temporary_errors = [
        "503",
        "429",
        "500",
        "502",
        "504",
        "service unavailable",
        "resource exhausted",
        "internal server error",
        "deadline exceeded",
        "timed out",
        "connection reset",
    ]

    return any(
        message in error_message
        for message in temporary_errors
    )


# --------------------------------------------------
# GENERATE AI RESPONSE
# --------------------------------------------------

def generate_answer(
    question,
    stock_context,
    chat_history=None
):

    if not question or not question.strip():
        return "Please enter a question."

    try:

        client = get_gemini_client()

        context_text = json.dumps(
            stock_context,
            indent=2,
            ensure_ascii=False,
            default=str
        )

        history_text = ""

        if chat_history:

            history_text = "\n".join(
                [
                    f"{message['role']}: {message['content']}"
                    for message in chat_history[-6:]
                ]
            )

        prompt = f"""
CURRENT STOCK DATA:

{context_text}

PREVIOUS CONVERSATION:

{history_text if history_text else "No previous conversation."}

USER QUESTION:

{question}

Answer the user's question using the supplied stock data.
If the data does not contain the information needed,
explain that limitation instead of guessing.
"""

        # Retry temporary Gemini API failures

        for attempt in range(MAX_RETRIES + 1):

            try:

                response = client.models.generate_content(
                    model=GEMINI_MODEL,
                    contents=prompt,
                    config=types.GenerateContentConfig(
                        system_instruction=SYSTEM_INSTRUCTION,
                        temperature=0.3,
                        max_output_tokens=900
                    )
                )

                if not response.text:
                    return (
                        "Gemini did not return a response. "
                        "Please try again."
                    )

                return response.text.strip()

            except Exception as error:

                if (
                    not is_retryable_error(error)
                    or attempt == MAX_RETRIES
                ):
                    raise

                delay = RETRY_DELAY * (2 ** attempt)

                print(
                    f"Gemini temporary error: {error}. "
                    f"Retrying in {delay} seconds "
                    f"(attempt {attempt + 1}/{MAX_RETRIES})..."
                )

                time.sleep(delay)

    except Exception as error:

        print(f"Gemini Assistant Error: {error}")

        if is_retryable_error(error):

            return (
                "Gemini is temporarily experiencing high demand. "
                "Automatic retries were unsuccessful. "
                "Please wait a moment and try again."
            )

        return (
            "Sorry, I could not generate a response. "
            "Please check your API key, internet connection "
            "and Gemini API configuration."
        )
